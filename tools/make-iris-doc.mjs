/* Writes docs/IRIS-MAP.md from src/iris.ts.

   The worksheet somebody fills in while sitting in front of IRIS, generated
   from the map itself so it cannot describe fields the code does not have.

       npm run iris          rewrite the worksheet
       npm run iris:check    fail if it is out of date (CI)

   Deliberately one-way: the document is generated from the code, never parsed
   back into it. Transcribed codes are typed into src/iris.ts, where they are
   reviewable in a diff, and the worksheet is regenerated. */
import {writeFileSync,readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';

const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const out=join(root,'docs','IRIS-MAP.md');

const {IRIS_FIELDS,IRIS_MAP_VERSION,irisStatus,IRIS_DRAFT_WARNING,validateIrisMap,isVerifiedIrisField}=await import('../src/iris.ts');

validateIrisMap();
const status=irisStatus();
for(const year of [...new Set(IRIS_FIELDS.map(f=>f.taxYear))].sort()){
 const missing=IRIS_FIELDS.filter(f=>f.taxYear===year&&!isVerifiedIrisField(f));
 console.log(`TY${year} missing verified codes (${missing.length}): ${missing.map(f=>f.id).join(', ')}`);
}
const forms=[...new Set(IRIS_FIELDS.map(f=>f.form))];
const tick=f=>f.verified?'yes':'**no**';
const cell=v=>v?String(v).replace(/\|/g,'\\|'):'—';

const lines=[
 '# IRIS field map',
 '',
 `_Map version \`${IRIS_MAP_VERSION}\`. Generated from \`src/iris.ts\` by \`tools/make-iris-doc.mjs\` —`
 +' edit the source, then run `npm run iris`. Do not edit this file._',
 '',
 `**${status.verified} of ${status.total} fields transcribed.** `
 +(status.ready
  ?'Every required field has been checked against a real return.'
  :`${status.missing.length} required field${status.missing.length===1?'':'s'} still unverified, `
   +`so the map is a draft: \`${status.missing.join('`, `')}\`.`),
 '',
 '## Why the codes are blank',
 '',
 IRIS_DRAFT_WARNING,
 '',
 'A wrong field code does not show a wrong screen. It files a figure in the wrong'
 +' box, which is a misdeclaration carrying the customer’s name — so no code here'
 +' is ever written from memory, from a blog post, or from another tool’s output.'
 +' The sections of law are different: those come from `docs/TAX-RULES.md`, which'
 +' was checked against the Ordinance, and they are safe to rely on.',
 '',
 '## How to transcribe one',
 '',
 '1. Sign in to IRIS and **start, without submitting**, a return of income for the'
 +' right tax year and taxpayer type (individual, non-salaried business).',
 '2. Navigate to the path in the table below.',
 '3. Copy the field’s code and its label **exactly as IRIS prints them**, including'
 +' any odd capitalisation or spacing.',
 '4. In `src/iris.ts`, set `code`, `irisLabel`, `verified:true`, and put your'
 +' source (`IRIS screen` or `FBR return form SRO …`), `checkedOn` and `checkedBy`.',
 '5. Run `npm run iris` and commit the source and the regenerated worksheet together.',
 '',
 'Leave anything you could not find unverified. A blank is honest; a guess is not.'
 +' Two fields are marked optional because a return may not show them at all:'
 +' the s.4AB surcharge appears only above the threshold, and the s.154B row only'
 +' from TY2027.',
 '',
 '## Fields',
];

for(const form of forms){
 const group=IRIS_FIELDS.filter(f=>f.form===form);
 lines.push('',`### ${form}`,'',
  '| Hisaab figure | Transcribed | IRIS code | IRIS label | Years | Law |',
  '|---|---|---|---|---|---|');
 for(const f of group)
  lines.push(`| ${cell(f.label)} | ${tick(f)} | ${cell(f.code)} | ${cell(f.irisLabel)} `
   +`| ${String(f.taxYear)} | ${cell(f.law)} |`);
 lines.push('');
 for(const f of group)
  lines.push(`**${f.label}**${f.required?'':' (optional)'} — \`${f.id}\`, from \`${f.figure}\`.`,
   '',`Where to look: ${f.verified?f.irisPath:'Unverified — no filing instruction'}`,'',f.note,'');
}

lines.push('---','',
 'Hisaab is not connected to IRIS. It cannot sign in, submit, or read anything from'
 +' FBR, and this map does not change that: it tells a person where to type a number'
 +' they already have. Nothing here is tax advice, and the figures it points at are'
 +' estimates the app itself describes as needing a practitioner’s review.');

const rendered=lines.join('\n')+'\n';

if(process.argv.includes('--check')){
 let existing='';
 try{existing=readFileSync(out,'utf8');}catch{/* missing counts as out of date */}
 if(existing!==rendered){
  console.error('docs/IRIS-MAP.md is out of date with src/iris.ts. Run: npm run iris');
  process.exit(1);
 }
 console.log(`docs/IRIS-MAP.md matches src/iris.ts (${status.verified}/${status.total} transcribed).`);
}else{
 writeFileSync(out,rendered);
 console.log(`wrote docs/IRIS-MAP.md — ${status.verified}/${status.total} transcribed, `
  +`${status.ready?'map is complete':'map is a draft'}`);
}
